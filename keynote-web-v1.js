deck.addEventListener("click", (event) => {
  if (document.body.classList.contains("overview")) {
    const slide = event.target.closest(".slide");
    if (!slide) return;
    toggleOverview(false);
    goTo(Number(slide.dataset.index));
    return;
  }
  const toggleButton = event.target.closest(".video-toggle");
  if (toggleButton) {
    event.stopPropagation();
    const slide = toggleButton.closest(".video-slide");
    const video = slide?.querySelector("video");
    if (!video) return;
    if (video.dataset.src && !video.src) loadSlideAssets(Number(slide.dataset.index), true);
    if (video.paused) {
      video.play().catch(() => slide.classList.add("video-failed"));
    } else {
      video.pause();
    }
    return;
  }
  if (event.target.closest(".video-next, .video-advance")) {
    event.stopPropagation();
    goTo(current + 1);
    return;
  }
  const clickedVideo = event.target.closest("video");
  if (clickedVideo) {
    const clickedControls = event.clientY > window.innerHeight - 72;
    if (clickedControls) return;
  }
  if (event.target.closest("button, a")) return;
  goTo(current + 1);
});

deckBar?.addEventListener("click", (event) => {
  if (event.target.closest("button, a")) return;
  goTo(current + 1);
});

deck.addEventListener("play", (event) => {
  const slide = event.target.closest(".video-slide");
  slide?.classList.add("playing");
}, true);

deck.addEventListener("pause", (event) => {
  const slide = event.target.closest(".video-slide");
  slide?.classList.remove("playing");
}, true);

window.addEventListener("keydown", (event) => {
  const activeTag = document.activeElement?.tagName?.toLowerCase();
  const isVideoControl = activeTag === "video" || event.target?.closest?.("video");
  if (isVideoControl && event.key === " ") return;
  if (event.key === "ArrowRight" || event.key === " ") {
    event.preventDefault();
    event.stopPropagation();
    goTo(current + 1);
  }
  if (event.key === "ArrowLeft") {
    event.preventDefault();
    event.stopPropagation();
    goTo(current - 1);
  }
  if (event.key.toLowerCase() === "n") toggleNotes();
  if (event.key.toLowerCase() === "o") toggleOverview();
  if (event.key === "Escape") {
    toggleNotes(false);
    toggleOverview(false);
  }
}, true);

window.addEventListener("hashchange", () => {
  const match = location.hash.match(/slide-(\d+)/);
  if (match) goTo(Number(match[1]) - 1);
});
