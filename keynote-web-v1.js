function slideClass(slide) {
  const classes = ["slide"];
  if (slide.type === "cover") classes.push("cover", "media");
  if (slide.type === "media") classes.push("media");
  if (slide.type === "quote") classes.push("quote-slide");
  if (!slide.type || slide.type === "statement") classes.push("text-slide");
  if (slide.type === "method-map") classes.push("method-slide");
  return classes.join(" ");
}

function lazyImage(src, alt = "", extra = "") {
  return `<img data-src="${src}" alt="${alt}" decoding="async" loading="lazy"${extra}>`;
}

function renderSlide(slide, index) {
  const section = document.createElement("section");
  section.id = `slide-${index + 1}`;
  section.className = slideClass(slide);
  section.dataset.index = index;
  section.dataset.number = String(index + 1).padStart(2, "0");
  section.dataset.kicker = slide.kicker || "";
  section.dataset.title = slide.title || "";

  const imageStyle = slide.imagePosition ? ` style="object-position: ${slide.imagePosition}"` : "";
  const mediaBg = slide.type === "cover" || slide.type === "media"
    ? `<div class="media-bg">${lazyImage(slide.image, "", imageStyle)}</div>`
    : "";
  const visual = slide.type === "visual"
    ? `<div class="visual">${lazyImage(slide.image, slide.title)}</div>`
    : slide.image && !["cover", "media", "final"].includes(slide.type)
      ? `<div class="visual cover-img">${lazyImage(slide.image, slide.title)}</div>`
      : "";
  const chips = slide.chips
    ? `<div class="chips">${slide.chips.map((chip) => `<span class="chip">${chip}</span>`).join("")}</div>`
    : "";
  const proof = slide.proof ? `<div class="proof">${slide.proof}</div>` : "";
  const detail = slide.detail ? `<p class="detail">${slide.detail}</p>` : "";

  if (slide.type === "cover") {
    section.innerHTML = `
      ${mediaBg}
      <div class="stage">
        <p class="kicker">${slide.kicker}</p>
        <h1>${slide.title}</h1>
        <p class="body">${slide.subtitle}</p>
        ${detail}
        <div class="meta">${slide.meta.map((item) => `<span>${item}</span>`).join("")}</div>
      </div>
      <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
    return section;
  }

  if (slide.type === "quote") {
    section.innerHTML = `
      <div class="stage">
        <p class="kicker">${slide.title}</p>
        <div class="quote">${slide.body}</div>
        ${detail}
      </div>
      <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
    return section;
  }

  if (slide.type === "media") {
    section.innerHTML = `
      ${mediaBg}
      <div class="stage">
        <p class="kicker">${slide.kicker || ""}</p>
        <h2>${slide.title}</h2>
        ${slide.body ? `<p class="body">${slide.body}</p>` : ""}
        ${detail}
        ${proof}
        ${chips}
      </div>
      <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
    return section;
  }

  if (slide.type === "statement") {
    section.classList.add("statement-slide");
    section.innerHTML = `
      <div class="stage">
        <p class="kicker">${slide.kicker || ""}</p>
        <h2>${slide.title}</h2>
        <p class="statement-body">${slide.body}</p>
        ${detail}
      </div>
      <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
    return section;
  }

  if (slide.type === "video") {
    section.classList.add("video-slide");
    section.innerHTML = `
      <video class="slide-video" data-src="${slide.video}" ${slide.poster ? `data-poster="${slide.poster}"` : ""} controls playsinline preload="none"></video>
      <button class="video-advance" type="button" aria-label="下一页"></button>
      <button class="video-toggle" type="button" aria-label="播放或暂停">▶</button>
      <button class="video-next" type="button" aria-label="下一页">›</button>
      <div class="video-error" role="status">视频暂时无法播放，请检查文件格式或浏览器权限。</div>
      <div class="video-caption">
        <p class="kicker">${slide.kicker || ""}</p>
        <h2>${slide.title}</h2>
        ${slide.body ? `<p>${slide.body}</p>` : ""}
      </div>
      <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
    return section;
  }

  if (slide.type === "method-map") {
    const nodes = (slide.nodes || []).map((node, nodeIndex) => `
      <div class="method-node">
        <span class="method-node-index">${String(nodeIndex + 1).padStart(2, "0")}</span>
        <strong>${node.label}</strong>
        <small>${node.sub || ""}</small>
      </div>
      ${nodeIndex < (slide.nodes || []).length - 1 ? `<span class="method-arrow">›</span>` : ""}
    `).join("");
    section.innerHTML = `
      <div class="stage method-stage">
        <p class="kicker">${slide.kicker || ""}</p>
        <h2>${slide.title}</h2>
        ${slide.body ? `<p class="body">${slide.body}</p>` : ""}
        ${detail}
        <div class="method-chain">${nodes}</div>
      </div>
      <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
    return section;
  }

  if (slide.type === "thanks") {
    const logos = (slide.logos || []).map((logo) => `
      <figure class="school-logo">
        ${lazyImage(logo.image, logo.label)}
        <figcaption>${logo.label}</figcaption>
      </figure>
    `).join("");
    section.innerHTML = `
      <div class="stage thanks-stage">
        <div class="thanks-copy">
          <p class="kicker">${slide.kicker || ""}</p>
          <h2>${slide.title}</h2>
          ${slide.body ? `<p class="body">${slide.body}</p>` : ""}
        </div>
        <div class="school-logos">${logos}</div>
      </div>
      <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
    return section;
  }

  if (slide.type === "contact") {
    const qrs = (slide.qrs || []).map((qr) => `
      <figure class="contact-qr ${qr.pending ? "pending" : ""}">
        ${qr.pending ? `<div class="qr-placeholder">待补</div>` : lazyImage(qr.image, qr.label)}
        <figcaption>
          <strong>${qr.label}</strong>
          <span>${qr.url || ""}</span>
        </figcaption>
      </figure>
    `).join("");
    section.innerHTML = `
      <div class="stage contact-stage">
        <div class="contact-copy">
          <p class="kicker">${slide.kicker || ""}</p>
          <h2>${slide.title}</h2>
          ${slide.body ? `<p class="body">${slide.body}</p>` : ""}
        </div>
        <div class="contact-qrs">${qrs}</div>
      </div>
      <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
    return section;
  }

  if (slide.type === "source") {
    section.classList.add("source-slide");
    section.innerHTML = `
      <div class="source-page">${lazyImage(slide.image, slide.title)}</div>
      ${slide.hideCaption ? "" : `<div class="source-caption">
        <p class="kicker">${slide.kicker || ""}</p>
        <h2>${slide.title}</h2>
        ${slide.body ? `<p>${slide.body}</p>` : ""}
      </div>`}
      <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
    return section;
  }

  if (slide.type === "fullbleed") {
    section.classList.add("fullbleed");
    if (slide.fit === "contain") section.classList.add("fit-contain");
    if (slide.infoDense) section.classList.add("info-dense");
    section.innerHTML = `
      <div class="fullbleed-bg">${lazyImage(slide.image, slide.title)}</div>
      ${slide.hideCaption ? "" : `<div class="fullbleed-copy">
        <p class="kicker">${slide.kicker || ""}</p>
        <h2>${slide.title}</h2>
        ${slide.body ? `<p>${slide.body}</p>` : ""}
      </div>`}
      <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
    return section;
  }

  if (slide.type === "visual" || visual) {
    section.classList.add("image-split");
    section.innerHTML = `
      ${mediaBg}
      <div class="stage two">
        <div>
          <p class="kicker">${slide.kicker || ""}</p>
          <h2>${slide.title}</h2>
          ${slide.body ? `<p class="body">${slide.body}</p>` : ""}
          ${detail}
          ${proof}
          ${chips}
        </div>
        ${visual}
      </div>
      <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
    return section;
  }

  section.innerHTML = `
    <div class="stage">
      <p class="kicker">${slide.kicker || ""}</p>
      <h2>${slide.title}</h2>
      <p class="body">${slide.body || ""}</p>
      ${detail}
      ${proof}
      ${chips}
    </div>
    <div class="number">${String(index + 1).padStart(2, "0")}</div>`;
  return section;
}

function renderDeck() {
  deck.innerHTML = "";
  slides.forEach((slide, index) => deck.appendChild(renderSlide(slide, index)));
}

function updateNotes() {
  const notes = slides[current].notes || [];
  notesContent.innerHTML = `<ul>${notes.map((note) => `<li>${note}</li>`).join("")}</ul>`;
}

function updateActiveChapter() {
  chapterLinks.forEach((link) => {
    const target = Number(link.getAttribute("href").replace("#slide-", "")) - 1;
    link.classList.toggle("active", current >= target);
  });
}

function loadSlideAssets(index, includeVideo = false) {
  const slide = deck.querySelector(`.slide[data-index="${index}"]`);
  if (!slide) return;
  slide.querySelectorAll("img[data-src]").forEach((img) => {
    img.src = img.dataset.src;
    img.removeAttribute("data-src");
  });
  slide.querySelectorAll("video[data-src]").forEach((video) => {
    if (video.dataset.poster && !video.poster) video.poster = video.dataset.poster;
    if (!includeVideo) return;
    if (!video.src) {
      video.src = video.dataset.src;
      video.preload = "metadata";
      video.load();
    }
  });
}

function prepareNearbyAssets(index) {
  for (let offset = -2; offset <= 3; offset += 1) {
    loadSlideAssets(index + offset, false);
  }
}

function prepareAllImages() {
  document.querySelectorAll(".slide").forEach((slide) => {
    loadSlideAssets(Number(slide.dataset.index), false);
  });
}

function goTo(index) {
  document.querySelectorAll("video").forEach((video) => {
    if (!video.paused) video.pause();
  });
  current = Math.max(0, Math.min(slides.length - 1, index));
  document.querySelectorAll(".slide").forEach((slide, i) => {
    slide.classList.toggle("active", i === current);
  });
  progressBar.style.width = `${((current + 1) / slides.length) * 100}%`;
  const activeSlide = slides[current];
  const cleanStage = (activeSlide.type === "source" || activeSlide.type === "fullbleed") && activeSlide.hideCaption;
  document.body.classList.toggle("clean-stage", cleanStage);
  prepareNearbyAssets(current);
  updateNotes();
  updateActiveChapter();
  if (!document.body.classList.contains("overview")) {
    history.replaceState(null, "", `#slide-${current + 1}`);
  }
}

function toggleNotes(force) {
  const open = force ?? !notesPanel.classList.contains("open");
  notesPanel.classList.toggle("open", open);
  notesToggle.classList.toggle("active", open);
}

function toggleOverview(force) {
  const open = force ?? !document.body.classList.contains("overview");
  document.body.classList.toggle("overview", open);
  overviewToggle.classList.toggle("active", open);
  if (open) prepareAllImages();
  if (!open) goTo(current);
}

